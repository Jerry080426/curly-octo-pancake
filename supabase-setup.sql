-- 时之洄游 · 模型匿名评分与留言
-- Supabase → SQL Editor → New query → 粘贴运行

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  nickname text not null default '匿名'
    check (char_length(nickname) between 1 and 16),
  content text not null
    check (char_length(content) between 1 and 120),
  rating smallint not null default 5
    check (rating between 1 and 5),
  is_hidden boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.messages add column if not exists rating smallint;
update public.messages set rating = 5 where rating is null;
alter table public.messages alter column rating set default 5;
alter table public.messages alter column rating set not null;
alter table public.messages drop column if exists tag;
alter table public.messages drop constraint if exists messages_rating_check;
alter table public.messages add constraint messages_rating_check check (rating between 1 and 5);

alter table public.messages enable row level security;
drop policy if exists "public read visible messages" on public.messages;
drop policy if exists "public insert messages" on public.messages;
create policy "public read visible messages" on public.messages for select to anon using (is_hidden = false);
create policy "public insert messages" on public.messages for insert to anon with check (is_hidden = false and rating between 1 and 5);
grant usage on schema public to anon;
grant select, insert on public.messages to anon;
grant usage, select on sequence public.messages_id_seq to anon;
create index if not exists messages_created_at_idx on public.messages (created_at desc);

-- 在 Table Editor 中把 is_hidden 改为 true，即可隐藏某条留言。
